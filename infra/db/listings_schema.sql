-- Tables of one listing snapshot lst_<snapshot_id> (data contract, Listings; F4.4). Executed by
-- publish_listings with search_path set to the new schema. No names or contact data (O24).
CREATE TABLE listings (
    listing_id           text PRIMARY KEY,
    source               text NOT NULL,
    source_url           text NOT NULL,
    kind                 text NOT NULL CHECK (kind IN ('wg_room', 'studio', 'flat')),
    title                text,
    rent_total_eur       integer,
    rent_cold_eur        integer,
    utilities_eur        integer,
    other_costs_eur      integer,
    deposit_eur          integer,
    transfer_fee_eur     integer,
    size_m2              real,
    flat_size_m2         real,
    rooms                real,
    household_size       smallint,
    flatmates_women      smallint,
    flatmates_men        smallint,
    flatmates_diverse    smallint,
    flatmates_age_min    smallint,
    flatmates_age_max    smallint,
    looking_for_gender   text,
    looking_for_age_min  smallint,
    looking_for_age_max  smallint,
    wg_types             text[],
    languages            text[],
    smoking              text,
    available_from       date,
    available_to         date,
    furnished            text,
    features             text[],
    district             text,
    postcode             text,
    address_text         text,
    geocode_precision    text CHECK (geocode_precision IN ('house', 'street', 'marker')),
    cell_id              text,
    geom                 geometry(Point, 25832),
    image_urls           text[],
    description_excerpt  text,
    online_since         timestamptz,
    first_seen           timestamptz NOT NULL,
    last_seen            timestamptz NOT NULL,
    fetched_at           timestamptz,
    parse_warnings       text[]
);
CREATE INDEX listings_cell ON listings (cell_id);
CREATE INDEX listings_geom ON listings USING gist (geom);
